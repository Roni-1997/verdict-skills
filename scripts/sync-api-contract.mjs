#!/usr/bin/env node
// Copy the Verdict API's OpenAPI document (docs/api/openapi.json in the Verdict app repository) at a
// pinned commit into packages/core/api-contract, byte for byte, and record the pin in
// packages/core/api-contract/UPSTREAM.json plus a generated provenance constant in
// packages/core/src/api-contract.ts. Nothing is copied by hand: the file comes from the GitHub
// contents API at the pinned commit, the same way scripts/sync-engine.mjs copies the engine.
// Re-run with --commit <sha> to move the pin; then run check-api-contract.mjs.
//
//   node scripts/sync-api-contract.mjs [--commit <sha>]
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { fetchGithubFile, gitBlobSha1, sha256 } from './sync-engine.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const CONTRACT_DIR = 'packages/core/api-contract';
export const UPSTREAM_PATH = `${CONTRACT_DIR}/UPSTREAM.json`;
export const GENERATED_PATH = 'packages/core/src/api-contract.ts';

/** The contract consists of one file; check-api-contract.mjs requires UPSTREAM.json to list exactly this. */
export const DEFAULTS = {
  repo: 'Roni-1997/verdict',
  commit: '352b2352918cfb9d0616ae19cd4f80346e1d44a9',
  files: [{ local: `${CONTRACT_DIR}/openapi.json`, upstream: 'docs/api/openapi.json' }],
};

function readExisting() {
  try {
    return JSON.parse(readFileSync(resolve(root, UPSTREAM_PATH), 'utf8'));
  } catch {
    return null;
  }
}

function argValue(flag) {
  const i = process.argv.indexOf(flag);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

function main() {
  const existing = readExisting();
  const repo = existing?.repo ?? DEFAULTS.repo;
  const commit = argValue('--commit') ?? existing?.commit ?? DEFAULTS.commit;
  const files = (existing?.files ?? DEFAULTS.files).map((f) => ({ local: f.local, upstream: f.upstream }));
  const out = [];
  for (const f of files) {
    const { bytes, blobSha } = fetchGithubFile(repo, f.upstream, commit);
    if (gitBlobSha1(bytes) !== blobSha) throw new Error(`blob sha mismatch for ${f.upstream}: content did not decode to the blob GitHub reported`);
    // The document must parse: a contract that is not JSON pins nothing.
    JSON.parse(bytes.toString('utf8'));
    const target = resolve(root, f.local);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, bytes);
    out.push({ local: f.local, upstream: f.upstream, bytes: bytes.length, gitBlobSha1: blobSha, sha256: sha256(bytes) });
    process.stdout.write(`${f.local}  ${bytes.length} bytes  sha256 ${out.at(-1).sha256}\n`);
  }
  const record = { repo, commit, syncedAt: new Date().toISOString(), files: out };
  writeFileSync(resolve(root, UPSTREAM_PATH), `${JSON.stringify(record, null, 2)}\n`);
  writeFileSync(
    resolve(root, GENERATED_PATH),
    [
      '// Generated by scripts/sync-api-contract.mjs from packages/core/api-contract/UPSTREAM.json. Do not edit.',
      '/** The Verdict API contract (docs/api/openapi.json in the app repository) the hosted tools in remote.ts were built against. */',
      'export const API_CONTRACT = {',
      `  repo: ${JSON.stringify(repo)},`,
      `  commit: ${JSON.stringify(commit)},`,
      `  files: ${JSON.stringify(out.map((f) => ({ local: f.local, upstream: f.upstream, sha256: f.sha256 })), null, 2).replace(/\n/g, '\n  ')},`,
      '} as const;',
      '',
    ].join('\n'),
  );
  process.stdout.write(`pinned ${repo}@${commit} in ${UPSTREAM_PATH}\n`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();

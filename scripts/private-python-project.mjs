import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repository = fileURLToPath(new URL('..', import.meta.url));
const deployment = join(repository, 'deploy/private');
const sha256 = (value) => createHash('sha256').update(value).digest('hex');

function pins(source) {
  const result = [];
  for (const raw of source.split('\n')) {
    const line = raw.trim().replace(/\s*\\$/, '');
    if (!line || line.startsWith('#') || /^--hash=sha256:[a-f0-9]{64}$/.test(line)) continue;
    if (!/^[a-z0-9._-]+(?:\[[a-z0-9,._-]+\])?==[0-9][a-z0-9._+!-]*(?:\s*;.*)?$/i.test(line)
        && !/^[a-z0-9._-]+ @ git\+https:\/\/github\.com\/[a-z0-9._-]+\/[a-z0-9._-]+(?:\.git)?@[a-f0-9]{40}$/i.test(line)) throw new Error('Private Python dependencies require exact versions or full public Git commits');
    result.push(line);
  }
  return result;
}

export function pythonProject(requirements, overrides) {
  const sources = [];
  const dependencies = pins(requirements).map((pin) => {
    const git = /^([a-z0-9._-]+) @ git\+(https:\/\/github\.com\/[a-z0-9._-]+\/[a-z0-9._-]+)@([a-f0-9]{40})$/i.exec(pin);
    if (!git) return pin;
    sources.push(`${JSON.stringify(git[1])} = { git = ${JSON.stringify(git[2])}, rev = ${JSON.stringify(git[3])} }`);
    return git[1];
  });
  const lines = (values) => values.map((value) => `  ${JSON.stringify(value)},`).join('\n');
  return `# Generated by scripts/private-python-project.mjs; do not edit.\n# requirements-sha256: ${sha256(requirements)}\n# security-overrides-sha256: ${sha256(overrides)}\n[project]\nname = "verdict-private-signer"\nversion = "0.0.0"\nrequires-python = ">=3.12,<3.13"\ndependencies = [\n${lines(dependencies)}\n]\n\n[tool.uv]\npackage = false\noverride-dependencies = [\n${lines(pins(overrides))}\n]\n\n[[tool.uv.index]]\nname = "pypi"\nurl = "https://pypi.org/simple"\ndefault = true\n\n[tool.uv.sources]\n${sources.join('\n')}\n`;
}

async function inputs() {
  return { requirements: await readFile(join(repository, 'local-runner/requirements.lock'), 'utf8'),
    overrides: await readFile(join(repository, 'local-runner/security-overrides.in'), 'utf8') };
}

function witness(requirements, overrides, project, lock) {
  return { format: 'verdict-private-python/1', requirementsSha256: sha256(requirements), securityOverridesSha256: sha256(overrides),
    pyprojectSha256: sha256(project), uvLockSha256: sha256(lock) };
}

export async function verifyPrivatePythonProject() {
  const { requirements, overrides } = await inputs();
  const project = await readFile(join(deployment, 'pyproject.toml'), 'utf8');
  const lock = await readFile(join(deployment, 'uv.lock'), 'utf8');
  const expected = witness(requirements, overrides, project, lock);
  const recorded = JSON.parse(await readFile(join(deployment, 'python-lock.json'), 'utf8'));
  if (project !== pythonProject(requirements, overrides) || JSON.stringify(recorded) !== JSON.stringify(expected)) throw new Error('Private Python manifest/lock is stale; run node scripts/private-python-project.mjs, then verify a clean uv sync --locked');
  return expected;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.slice(2).join() === '--check') {
    process.stdout.write(`${JSON.stringify({ ok: true, ...await verifyPrivatePythonProject() })}\n`);
  } else {
    if (process.argv.length !== 2) throw new Error('Usage: node scripts/private-python-project.mjs [--check]');
    const { requirements, overrides } = await inputs();
    const project = pythonProject(requirements, overrides);
    await writeFile(join(deployment, 'pyproject.toml'), project);
    execFileSync('uv', ['lock', '--python', '3.12', '--directory', deployment], { stdio: 'inherit',
      env: { PATH: process.env.PATH ?? '/usr/bin:/bin', GIT_TERMINAL_PROMPT: '0' } });
    const lock = await readFile(join(deployment, 'uv.lock'), 'utf8');
    await writeFile(join(deployment, 'python-lock.json'), `${JSON.stringify(witness(requirements, overrides, project, lock), null, 2)}\n`);
    process.stdout.write(`${JSON.stringify({ ok: true, ...await verifyPrivatePythonProject() })}\n`);
  }
}
